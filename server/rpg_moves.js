  push('s6', 3, s6[2], meta.poison ? '特技' : '兵器', [22,30], 9, meta.poison ? { x: 3, sp: 'poison' } : meta.par ? { x: 3, sp: 'paralyze' } : meta.burn ? { x: 3, sp: 'burn' } : { x: 3 });
  push('s6', 4, s6[3], '被动', [0,0], 0, { at: B, av: 38, at2: A, av2: 42, df: 15, ref: 8 });
  // s7
  const s7 = meta.s7;
  push('s7', 1, s7[0], '兵器', [28,40], 13, { x: 3, ref: 10, ct: meta.ct, sp: (fid === 'kunlun' ? 'freeze' : (fid === 'tangmen' ? 'poison' : (fid === 'wudu' ? 'poison' : (fid === 'mingjiao' ? 'burn' : (meta.par ? 'paralyze' : null))))) });
