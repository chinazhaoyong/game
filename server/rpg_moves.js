  push('s4', 3, meta.w2[0], '内功', [0,0], 0, { mn: 20 });
  const s4l4 = { huashan:['惊雷剑',{}], kunlun:['昆仑玄冰掌',{sp:'freeze'}], tianshan:['天山冰焰掌',{df:2}], tangmen:['见血封喉',{sp:'poison',df:2}], mingjiao:['摩尼焚天掌',{sp:'burn',df:2}], wudu:['五毒噬心爪',{sp:'poison',df:2}], gaibang:['醉拳·中',{df:2}], salt:['漕运棍·精',{}], tiezhang:['铁掌帮重拳',{}], murong:['慕容连击',{df:2}], duanshi:['段氏轻剑',{}], diancang:['苍山掌',{df:2}], caobang:['漕运棍·猛',{df:2}], qinglong:['青龙重刀',{df:2}], bailian:['白莲幻扇',{sp:'paralyze'}], nan_gong:['南宫幻扇',{sp:'paralyze',df:2}] }[fid] || ['金蝉脱壳',{}];
  push('s4', 4, s4l4[0], '拳脚', [12,17], 5, { first: 1, ...s4l4[1] });
  push('s4', 5, meta.w2[1], '兵器', [13,18], 6, {});
  // s5
  push('s5', 1, stdS5L1Name(fid, meta), '被动', [0,0], 0, { at: A, av: 30, at2: B, av2: 28, hp: 35, mn: 20 });
  push('s5', 2, meta.w2[1] + '·真', '兵器', [17,23], 7, { x: 2 });
  push('s5', 3, meta.w1[1] + '·真', '拳脚', [17,23], 7, { x: 2 });
