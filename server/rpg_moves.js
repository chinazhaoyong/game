function buildAll() {
  const out = [];
  for (const g of GENERIC) out.push({ ...g, faction: null });
  for (const [fid, list] of [['shaolin', SHAOLIN], ['wudang', WUDANG]]) {
    list.forEach((m, i) => {
      const tier = ['s1','s1','s1','s1','s2','s2','s2','s2','s3','s3','s3','s3','s3','s4','s4','s4','s4','s4','s5','s5','s5','s5','s5','s6','s6','s6','s6','s7','s7','s7'][i];
      out.push({ faction: fid, tier, idx: i + 1, key: `${fid}_${tier}_l${i + 1}`, n: m.n, t: m.t, d: m.d, c: m.c, e: m.e });
    });
  }
  for (const [fid, meta] of Object.entries(FACTION_META)) {
    for (const r of buildStd(fid, meta)) {
      out.push({ faction: fid, tier: r.tier, idx: r.idx, key: `${fid}_${r.tier}_l${r.idx}`, n: r.name, t: r.type, d: r.dmg, c: r.cost, e: r.eff });
    }
  }
  return out;
}

